def cn(run, name=CN):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def h(doc, t, lv=1):
    p = doc.add_heading("", level=lv)
    cn(p.add_run(t))
    return p


def para(doc, t="", bold=False, size=10.5, color=None, italic=False):
    p = doc.add_paragraph()
    r = p.add_run(t)
    r.bold = bold
    r.italic = italic
    r.font.size = Pt(size)
    if color:
        r.font.color.rgb = color
    cn(r)
    return p


def mono(doc, t, wrap=94):
    for raw in t.split("\n"):
        line = raw
        while len(line) > wrap:
            cut = line.rfind(" ", 0, wrap)
            if cut < wrap // 2:
                cut = wrap
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.5)
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.space_after = Pt(0)
            r = p.add_run(line[:cut])
            r.font.name = MONO
            r.font.size = Pt(8.5)
            r._element.rPr.rFonts.set(qn("w:eastAsia"), MONO)
            line = line[cut:].lstrip()
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.5)
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(line)
        r.font.name = MONO
        r.font.size = Pt(8.5)
        r._element.rPr.rFonts.set(qn("w:eastAsia"), MONO)


def table(doc, hdr, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(hdr))
    t.style = "Light Grid Accent 1"
    for i, x in enumerate(hdr):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(x)
        r.bold = True
        r.font.size = Pt(9)
        cn(r)
    for row in rows:
        cs = t.add_row().cells
        for i, v in enumerate(row):
            cs[i].text = ""
            r = cs[i].paragraphs[0].add_run(str(v))
            r.font.size = Pt(9)
            cn(r)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return t


